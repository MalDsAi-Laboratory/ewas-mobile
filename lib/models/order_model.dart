class Order {
  final String? eid;
  final String? firstName;
  final String? lastName;
  final String? address;
  final String? assignee;
  final String? emailId;
  final String? orderStatus;
  final DateTime? orderDate;
  final String? orderDetails;

  Order({
    this.eid,
    this.firstName,
    this.lastName,
    this.address,
    this.assignee,
    this.emailId,
    this.orderStatus,
    this.orderDate,
    this.orderDetails,
  });
}
